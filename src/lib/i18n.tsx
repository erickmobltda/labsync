const localeMap: Record<Language, string> = {
  'pt-BR': 'pt-BR',
  en: 'en-US',
}

interface I18nContextValue {
  lang: Language
  setLang: (l: Language) => void
  t: (key: string, vars?: Record<string, string | number>) => string
  tBiomarker: (name: string) => string
  locale: string
  formatDate: (dateStr: string) => string
  formatDateShort: (dateStr: string) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

function readStoredLang(): Language {
  if (typeof window === 'undefined') return DEFAULT_LANG
  const stored = window.localStorage.getItem(STORAGE_KEY)
  if (stored === 'pt-BR' || stored === 'en') return stored
  return DEFAULT_LANG
}

function interpolate(str: string, vars?: Record<string, string | number>) {
  if (!vars) return str
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : `{${k}}`))
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(readStoredLang)

  useEffect(() => {
    if (typeof window !== 'undefined') {
      window.localStorage.setItem(STORAGE_KEY, lang)
      document.documentElement.lang = lang
    }
  }, [lang])

  const value = useMemo<I18nContextValue>(() => {
    const dict = dictionaries[lang]
    const locale = localeMap[lang]
    const t = (key: string, vars?: Record<string, string | number>) => {
      const raw = dict[key] ?? dictionaries.en[key] ?? key
      return interpolate(raw, vars)
    }
    const tBiomarker = (name: string) => dict[`biomarker.${name}`] ?? name
    const toDate = (dateStr: string) =>
      new Date(dateStr.includes('T') ? dateStr : dateStr + 'T00:00:00')
    const formatDate = (dateStr: string) =>
      toDate(dateStr).toLocaleDateString(locale, {
        year: 'numeric',
        month: 'short',
        day: 'numeric',
      })
    const formatDateShort = (dateStr: string) =>
      toDate(dateStr).toLocaleDateString(locale, {
        month: 'short',
        day: 'numeric',
        year: '2-digit',
      })
    return { lang, setLang: setLangState, t, tBiomarker, locale, formatDate, formatDateShort }
  }, [lang])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useT() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useT must be used within I18nProvider')
  return ctx
}
